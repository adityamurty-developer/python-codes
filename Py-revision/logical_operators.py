# AND operator --> both results should true
print(False and False)
print(False and True)
print(True and False)
print(True and True)

print(" ")

# OR operator --> atleast one should true
print(False or False)
print(False or True)
print(True or False)
print(True or True)

print(" ")

# NOT operator --> it reverse the result 
print(not True)
print(not False)