# You are given a word - Python and you have to print Pyt using string slicing

word = "Python"

print(word[0:2])  # Here Py is print instead of Pyt because end index is excluded and all the indexe's before end index is included from start index

print(word[0:3]) # Here Pyt is printed from 0 - 2 index and end index i.e. 3 is excluded