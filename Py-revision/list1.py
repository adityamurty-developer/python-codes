# List --> stores multiple value's inside a variable

l1 = ["Aditya", "Amit", "Shreya"]
print(l1)

# list can store same and different data types 
data = ["Aditya", 20, 7.6, True]

# Duplicate value's are allowed in a list 
nums = [20, 10, 20, 30]

# list are ordered so we can do list indexing
l2 = [10, 20, 30]
print(l2[0], l2[1], l2[2])

# list is mutable so, we can change existing element of a list 
l2[0] = 100
print(l2)