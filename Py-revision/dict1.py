# Dictionary --> stores data in key-value pair

student = {
    "name": "Rohan",
    "age": 20,
    "cgpa": 7.6,
    "skills": ["Py", "Django", "Cpp", "Dsa"]
}

print(student)

# Properties of Dictionary:

# It is mutable
# Keys should be unique
# Values can be duplicate
# Values can be accessed using key
# Different data types values can be stored
# It is unordered

# Accessing values 

print(student["name"])
print(student["age"])

# if key not exist then we will get a keyError