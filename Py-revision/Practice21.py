# String Repetition

word = "Hello"
print((word + " ") * 3)  # prints "Hello" 3 times

print("")

# String in / not in --> checks if any char / substring is present inside a string or not

word1 = "Python"

print("P" in word1)
print("z" in word1)
print("z" not in word1)

word2 = "Programming language"

print("language" in word2)

print("")